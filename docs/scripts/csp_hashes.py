#!/usr/bin/env python3
"""Write the nginx security headers for the built documentation site.

Docusaurus puts a few small inline scripts in every page (theme selection, the base URL check).
A Content-Security-Policy that allows `'unsafe-inline'` would also allow an injected script.
This script reads the built HTML, hashes each inline script that the browser runs, and puts
only those hashes in the policy. A new Docusaurus version that changes a script gets a new hash
at the next build, with no manual step.

Usage:
    python docs/scripts/csp_hashes.py docs/build /etc/nginx/snippets/security-headers.conf
"""

from __future__ import annotations

import base64
import hashlib
import re
import sys
from pathlib import Path

SCRIPT_RE = re.compile(r"<script(?P<attrs>[^>]*)>(?P<body>.*?)</script>", re.DOTALL | re.IGNORECASE)
DATA_TYPES = ("application/ld+json", "application/json")

POLICY = (
    "default-src 'self'; script-src 'self' {hashes}; style-src 'self'; "
    "style-src-attr 'unsafe-inline'; img-src 'self' data:; font-src 'self'; connect-src 'self'; "
    "object-src 'none'; base-uri 'self'; form-action 'self'; frame-ancestors 'none'"
)

HEADERS = """\
# Generated by docs/scripts/csp_hashes.py at build time. Do not edit.
add_header Content-Security-Policy "{policy}" always;
add_header X-Content-Type-Options "nosniff" always;
add_header Referrer-Policy "strict-origin-when-cross-origin" always;
add_header Cross-Origin-Opener-Policy "same-origin" always;
add_header X-Robots-Tag "noindex, nofollow" always;
"""


def inline_script_hashes(build_dir: Path) -> list[str]:
    """Return the sorted CSP hash sources of all inline scripts that the browser runs.

    Args:
        build_dir: The folder that `docusaurus build` wrote.

    Returns:
        Hash sources like `'sha256-abc...='`. Scripts with a `src` attribute and data blocks
        such as JSON-LD are skipped. They are not code that the policy must allow.
    """
    found: set[str] = set()
    for page in build_dir.rglob("*.html"):
        for match in SCRIPT_RE.finditer(page.read_text(encoding="utf-8")):
            attrs = match.group("attrs").lower()
            if " src=" in f" {attrs}" or any(kind in attrs for kind in DATA_TYPES):
                continue
            digest = hashlib.sha256(match.group("body").encode("utf-8")).digest()
            found.add("'sha256-" + base64.b64encode(digest).decode("ascii") + "'")
    return sorted(found)


def render(hashes: list[str]) -> str:
    """Return the nginx snippet for the given script hashes."""
    return HEADERS.format(policy=POLICY.format(hashes=" ".join(hashes)))


def main(argv: list[str]) -> int:
    """Read the build folder in `argv[0]` and write the snippet to the file in `argv[1]`."""
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    build_dir, target = Path(argv[0]), Path(argv[1])
    hashes = inline_script_hashes(build_dir)
    if not hashes:
        print("No inline script found. Check the build folder.", file=sys.stderr)
        return 1
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(hashes), encoding="utf-8")
    print(f"Wrote {len(hashes)} script hashes to {target}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
